    private void BtnVenderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnVenderActionPerformed
        dao.ProductoDao productoDAO = new dao.ProductoDao();
        dao.VentaDao ventaDAO = new dao.VentaDao();

    
        model.Producto prodSeleccionado = (model.Producto) CajaProducto.getSelectedItem();
        
        if (prodSeleccionado == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un producto.");
            return;
        }

        try {
            int cantidadVender = Integer.parseInt(CajaCantidad.getSelectedItem().toString());

            if (prodSeleccionado.getCantidad() < cantidadVender) {
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "No hay suficiente stock. Solo quedan: " + prodSeleccionado.getCantidad() + " unidades.", 
                    "Stock Insuficiente", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            double precioTotal = prodSeleccionado.getPrecio() * cantidadVender;

            boolean ventaRegistrada = ventaDAO.registrarVenta(
                prodSeleccionado.getIdProducto(), 
                prodSeleccionado.getCategoria().getIdCategoria(), 
                prodSeleccionado.getNombre(), 
                cantidadVender, 
                precioTotal
            );

            if (ventaRegistrada) {
                productoDAO.restarStock(prodSeleccionado.getIdProducto(), cantidadVender);
                
                prodSeleccionado.setCantidad(prodSeleccionado.getCantidad() - cantidadVender);

                javax.swing.JOptionPane.showMessageDialog(this, "Venta realizada con éxito.\nTotal cobrado: $" + precioTotal);

                javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) TablaVentas.getModel();
                Object[] fila = new Object[3];
                fila[0] = prodSeleccionado.getNombre();
                fila[1] = cantidadVender;
                fila[2] = precioTotal;
                modelo.addRow(fila);
                
                if (ventanaPrincipal != null) {
                    ventanaPrincipal.actualizarTablaExterna();
                }

            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Error al registrar la venta en la base de datos.");
            }

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, seleccione una cantidad válida.");
        }
    }//GEN-LAST:event_BtnVenderActionPerformed

    private void CajaProductoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CajaProductoActionPerformed
        model.Producto prodSeleccionado = (model.Producto) CajaProducto.getSelectedItem();
        
        if (prodSeleccionado != null) {
            

            CajaCantidad.removeAllItems();
            

            int stockDisponible = prodSeleccionado.getCantidad();
            
            if (stockDisponible > 0) {
                for (int i = 1; i <= stockDisponible; i++) {
                    CajaCantidad.addItem(String.valueOf(i));
                }
            } else {
                CajaCantidad.addItem("0");
            }
        }
    }//GEN-LAST:event_CajaProductoActionPerformed

