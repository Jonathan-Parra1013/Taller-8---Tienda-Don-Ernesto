    private void cargarProductos() {

        CajaProducto.removeAllItems();
        
        dao.ProductoDao productoDAO = new dao.ProductoDao();
        java.util.List<model.Producto> listaProductos = productoDAO.listar();
        
        for (model.Producto p : listaProductos) {
            if (p.getCantidad() > 0) {
                CajaProducto.addItem(p);
            }
        }
    }
    
    private void cargarHistorialVentas() {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) TablaVentas.getModel();
        modelo.setRowCount(0); 
        
        dao.VentaDao ventaDAO = new dao.VentaDao();
        java.util.List<Object[]> historial = ventaDAO.listarVentas();
        
        for (Object[] fila : historial) {
            modelo.addRow(fila);
        }
        
    }
